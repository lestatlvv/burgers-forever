"use strict";

/**
 * Register Windows auto-start so both services + fullscreen kiosk open after login.
 *
 * Prefers a Scheduled Task (BurgersForeverKiosk). If schtasks is denied,
 * falls back to a .cmd file in the Startup folder (no COM / admin needed).
 */

const { spawnSync } = require("child_process");
const fs = require("fs");
const path = require("path");
const { isWin, STORE_ROOT } = require("./paths");

const TASK_NAME = "BurgersForeverKiosk";
const STARTUP_CMD_NAME = "BurgersForeverKiosk.cmd";
const BOOT_CMD = path.join(STORE_ROOT, "scripts", "boot-kiosk.cmd");
const BOOT_JS = path.join(STORE_ROOT, "scripts", "boot-kiosk.js");

function fail(message) {
  console.error(message);
  process.exit(1);
}

function run(command, args) {
  return spawnSync(command, args, {
    encoding: "utf8",
    windowsHide: true,
  });
}

function startupDir() {
  return path.join(
    process.env.APPDATA || "",
    "Microsoft",
    "Windows",
    "Start Menu",
    "Programs",
    "Startup"
  );
}

function startupCmdPath() {
  return path.join(startupDir(), STARTUP_CMD_NAME);
}

function installStartupCmd() {
  const dir = startupDir();
  if (!fs.existsSync(dir)) {
    fail(`Startup folder not found: ${dir}`);
  }

  const target = startupCmdPath();
  const contents =
    `@echo off\r\n` +
    `REM Auto-generated by npm run install:autostart - do not edit.\r\n` +
    `call "${BOOT_CMD}"\r\n`;

  fs.writeFileSync(target, contents, "utf8");
  return target;
}

function installScheduledTask() {
  run("schtasks", ["/Delete", "/TN", TASK_NAME, "/F"]);

  const user = process.env.USERNAME || process.env.USER;
  const createArgs = [
    "/Create",
    "/TN",
    TASK_NAME,
    "/TR",
    `"${BOOT_CMD}"`,
    "/SC",
    "ONLOGON",
    "/RL",
    "LIMITED",
    "/F",
  ];
  if (user) {
    createArgs.push("/RU", user);
  }

  const create = run("schtasks", createArgs);
  if (create.status !== 0) {
    return {
      ok: false,
      detail: (create.stderr || create.stdout || "schtasks failed").trim(),
    };
  }

  const delayPs = `
$task = Get-ScheduledTask -TaskName '${TASK_NAME}' -ErrorAction Stop
$trigger = $task.Triggers | Select-Object -First 1
$trigger.Delay = 'PT30S'
Set-ScheduledTask -TaskName '${TASK_NAME}' -Trigger $trigger | Out-Null
Write-Output 'Delay set to 30 seconds after logon.'
`;
  const delay = run("powershell", [
    "-NoProfile",
    "-ExecutionPolicy",
    "Bypass",
    "-Command",
    delayPs,
  ]);
  return {
    ok: true,
    delayOk: delay.status === 0,
    delayOut: (delay.stdout || "").trim(),
  };
}

function printSuccess({ mode, detail }) {
  console.log(`
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  Autostart installed (${mode})
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

  ${detail}

  On next Windows login this will:
    1. Start Demo Store (:5500) and Kokoro TTS (:7860)
    2. Open the kiosk UI in fullscreen (Chrome/Edge --kiosk)

  Test now (without reboot):
    npm run start:kiosk

  Remove autostart:
    npm run uninstall:autostart
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
`);
}

function main() {
  if (!isWin) {
    fail("install:autostart is only supported on Windows.");
  }

  if (!fs.existsSync(BOOT_CMD) || !fs.existsSync(BOOT_JS)) {
    fail(`Missing boot scripts under ${path.join(STORE_ROOT, "scripts")}`);
  }

  console.log("Trying Scheduled Task (ONLOGON)…");
  const task = installScheduledTask();
  if (task.ok) {
    if (task.delayOk && task.delayOut) {
      console.log(task.delayOut);
    } else if (!task.delayOk) {
      console.warn("Could not set 30s logon delay (task still created).");
    }
    printSuccess({
      mode: "Scheduled Task",
      detail: `Task name: ${TASK_NAME}\n  Trigger:   At user logon (+ ~30s delay)\n  Launcher:  ${BOOT_CMD}\n  Manage:    taskschd.msc → ${TASK_NAME}`,
    });
    return;
  }

  console.warn(`Scheduled Task failed: ${task.detail}`);
  console.warn("Falling back to Startup-folder launcher…");
  const startupFile = installStartupCmd();
  printSuccess({
    mode: "Startup folder",
    detail: `Launcher: ${startupFile}\n  Target:   ${BOOT_CMD}\n  Note:     Runs at logon via the Startup folder (no admin required).`,
  });
}

main();
