"use strict";

/**
 * Fallback-only: write a Startup-folder .cmd launcher.
 */

const fs = require("fs");
const path = require("path");
const { isWin, STORE_ROOT } = require("./paths");

const STARTUP_CMD_NAME = "BurgersForeverKiosk.cmd";
const BOOT_CMD = path.join(STORE_ROOT, "scripts", "boot-kiosk.cmd");

function fail(message) {
  console.error(message);
  process.exit(1);
}

function main() {
  if (!isWin) {
    fail("install:autostart:startup is only supported on Windows.");
  }
  if (!fs.existsSync(BOOT_CMD)) {
    fail(`Missing ${BOOT_CMD}`);
  }

  const startupDir = path.join(
    process.env.APPDATA || "",
    "Microsoft",
    "Windows",
    "Start Menu",
    "Programs",
    "Startup"
  );
  if (!fs.existsSync(startupDir)) {
    fail(`Startup folder not found: ${startupDir}`);
  }

  const target = path.join(startupDir, STARTUP_CMD_NAME);
  const contents =
    `@echo off\r\n` +
    `REM Auto-generated by npm run install:autostart:startup - do not edit.\r\n` +
    `call "${BOOT_CMD}"\r\n`;
  fs.writeFileSync(target, contents, "utf8");

  console.log(`
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
  Startup launcher installed
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

  File:   ${target}
  Target: ${BOOT_CMD}

  Runs at Windows logon (Startup folder).
  Test now: npm run start:kiosk
  Remove:   npm run uninstall:autostart
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
`);
}

main();
